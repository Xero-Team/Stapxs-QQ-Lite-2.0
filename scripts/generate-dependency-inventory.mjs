import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const packageJson = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'))
const sections = ['dependencies', 'devDependencies', 'optionalDependencies']
const entries = []

for (const section of sections) {
  for (const [name, requested] of Object.entries(packageJson[section] ?? {})) {
    const packagePath = path.join(root, 'node_modules', ...name.split('/'), 'package.json')
    let metadata
    try {
      metadata = JSON.parse(fs.readFileSync(packagePath, 'utf8'))
    } catch {
      metadata = { version: 'uninstalled', license: 'unknown' }
    }
    const license = typeof metadata.license === 'string'
      ? metadata.license
      : Array.isArray(metadata.licenses)
        ? metadata.licenses.map((item) => item.type ?? item).join(', ')
        : 'unknown'
    entries.push({ section, name, requested, version: metadata.version ?? 'unknown', license })
  }
}

entries.sort((left, right) => left.name.localeCompare(right.name))
const rows = entries.map((entry) => `| ${entry.name} | ${entry.section} | ${entry.requested} | ${entry.version} | ${entry.license.replaceAll('|', '\\|')} |`)
const output = `# Dependency inventory\n\nGenerated by \`yarn deps:inventory\`. Direct dependency versions are read from the installed tree; the complete transitive resolution remains in \`yarn.lock\`.\n\n| Package | Section | Requested | Installed | License |\n| --- | --- | --- | --- | --- |\n${rows.join('\n')}\n`
fs.writeFileSync(path.join(root, 'docs', 'DEPENDENCY_INVENTORY.md'), output)
