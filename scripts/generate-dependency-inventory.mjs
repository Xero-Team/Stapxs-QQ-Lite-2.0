import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const packageJson = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'))
const sections = ['dependencies', 'devDependencies', 'optionalDependencies']
// Some vendored packages omit a package.json license even though their source
// distribution includes a license file. Keep the attribution explicit here so
// the generated SBOM does not silently lose a license obligation.
const licenseOverrides = {
  'vue3-bcui': 'Apache-2.0',
}
const entries = []

for (const section of sections) {
  for (const [name, requested] of Object.entries(packageJson[section] ?? {})) {
    const packagePath = path.join(root, 'node_modules', ...name.split('/'), 'package.json')
    let metadata
    try {
      metadata = JSON.parse(fs.readFileSync(packagePath, 'utf8'))
    } catch {
      metadata = { version: 'uninstalled', license: 'unknown' }
    }
    const license = licenseOverrides[name] ?? (typeof metadata.license === 'string'
      ? metadata.license
      : Array.isArray(metadata.licenses)
        ? metadata.licenses.map((item) => item.type ?? item).join(', ')
        : 'unknown')
    entries.push({ section, name, requested, version: metadata.version ?? 'unknown', license })
  }
}

entries.sort((left, right) => left.name.localeCompare(right.name))
const rows = entries.map((entry) => `| ${entry.name} | ${entry.section} | ${entry.requested} | ${entry.version} | ${entry.license.replaceAll('|', '\\|')} |`)
const output = `# Dependency inventory\n\nGenerated by \`pnpm deps:inventory\`. Direct dependency versions are read from the installed tree; the complete transitive resolution remains in \`pnpm-lock.yaml\`.\n\n| Package | Section | Requested | Installed | License |\n| --- | --- | --- | --- | --- |\n${rows.join('\n')}\n`
fs.writeFileSync(path.join(root, 'docs', 'DEPENDENCY_INVENTORY.md'), output)

const sbom = {
  bomFormat: 'CycloneDX',
  specVersion: '1.5',
  serialNumber: 'urn:uuid:00000000-0000-4000-8000-000000000001',
  version: 1,
  metadata: {
    component: {
      type: 'application',
      name: packageJson.name,
      version: packageJson.version,
      author: packageJson.author,
      purl: `pkg:npm/${packageJson.name}@${packageJson.version}`,
    },
  },
  components: entries.filter((entry) => entry.version !== 'uninstalled').map((entry) => ({
    type: 'library',
    name: entry.name,
    version: entry.version,
    licenses: entry.license === 'unknown' ? undefined : [{ license: { name: entry.license } }],
    purl: `pkg:npm/${entry.name}@${entry.version}`,
    properties: [{ name: 'xero:dependency-scope', value: entry.section }],
  })),
}
fs.writeFileSync(path.join(root, 'docs', 'SBOM.cdx.json'), `${JSON.stringify(sbom, null, 2)}\n`)
